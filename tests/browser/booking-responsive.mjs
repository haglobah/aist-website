export default async function testResponsiveBooking(page) {
  const check = (value, message) => { if (!value) throw new Error(message) }
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('http://localhost:4321')
  const trigger = page.getByRole('button', { name: 'Book a 1:1', exact: true })
  const section = page.locator('#one-on-one-section')
  const dialog = page.locator('#one-on-one')
  check(await section.isVisible(), 'Mobile booking section must be visible')
  check(await section.evaluate(el => Boolean(el.compareDocumentPosition(document.querySelector('#feedback')) & Node.DOCUMENT_POSITION_FOLLOWING)), 'Booking must come before Contact us')
  await trigger.click()
  check(!await dialog.isVisible(), 'Mobile booking must not open a modal')
  await page.waitForFunction(() => Math.abs(document.querySelector('#one-on-one-section').getBoundingClientRect().top - 24) < 3)
  check(await trigger.getAttribute('aria-haspopup') === null, 'Mobile trigger must not announce a dialog')
  await section.locator('[data-organizer]').nth(1).click()
  await page.setViewportSize({ width: 1280, height: 900 })
  await section.waitFor({ state: 'hidden' })
  check(!await section.isVisible(), 'Desktop inline section must be hidden')
  await trigger.click()
  check(await dialog.isVisible(), 'Desktop booking must open a modal')
  check(await dialog.locator('[data-booking-heading]').textContent() === 'Book with Organizer 2', 'Resize must preserve selection')
  await page.setViewportSize({ width: 390, height: 844 })
  await dialog.waitFor({ state: 'hidden' })
  await section.waitFor({ state: 'visible' })
  check(!await dialog.isVisible(), 'Resize to mobile must close modal')
  check(await section.locator('[data-booking-heading]').textContent() === 'Book with Organizer 2', 'Returning to mobile must preserve selection')
  await section.locator('[data-organizer]').nth(2).click()
  check(await section.locator('[aria-pressed=true]').count() === 1, 'Moving picker must not duplicate handlers')
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  check(await page.evaluate(() => getComputedStyle(document.documentElement).scrollBehavior) === 'smooth', 'Page scrolling must be smooth')
  check(await dialog.evaluate(el => getComputedStyle(el).scrollBehavior) === 'smooth', 'Dialog scrolling must be smooth')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  check(await page.evaluate(() => getComputedStyle(document.documentElement).scrollBehavior) === 'auto', 'Reduced motion must disable smooth scrolling')
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.setViewportSize({ width: 1280, height: 900 })
  return 'Responsive booking, preserved selection and smooth scrolling passed.'
}
