export type UIKey = keyof typeof ui.en

export function useTranslations(lang: Lang) {
  return (key: UIKey, values: Record<string, string> = {}) =>
    ui[lang][key].replace(/\{(\w+)\}/g, (_, name) => values[name] ?? `{${name}}`)
}
